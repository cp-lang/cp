    fn generate_trait(&mut self, t: &TraitDecl) {
        writeln!(
            self.output,
            "const {} = struct {{ ptr: *anyopaque, vtable: *const VTable, const VTable = struct {{",
            t.ident.sym
        )
        .unwrap();
        self.indent();
        for m in &t.methods {
            let mut p_str = String::from("ptr: *anyopaque");
            for p in &m.params {
                p_str.push_str(", ");
                p_str.push_str(&self.map_type(&p.ty));
            }
            let ret = m
                .return_type
                .as_ref()
                .map(|t| self.map_type(t))
                .unwrap_or("void".to_string());
            self.writeln(&format!("{}: *const fn({}) {},", m.ident.sym, p_str, ret));
        }
        self.dedent();
        self.writeln("}; };\n");
    }

    fn generate_impl(&mut self, i: &ImplDecl) {
        self.writeln(&format!(
            "const vtable_{}_{} = {}.VTable {{ .{} = @ptrCast(&{}_{}) }};",
            i.trait_name.sym,
            i.target_name.sym,
            i.trait_name.sym,
            i.methods[0].ident.sym,
            i.target_name.sym,
            i.methods[0].ident.sym
        ));
        for m in &i.methods {
            self.generate_function_logic(m, Some(&i.target_name.sym));
        }
    }

    fn generate_enum(&mut self, e: &EnumDecl) {
        let enum_type = if e.variants.iter().any(|v| v.value.is_some()) {
            "enum(u32)"
        } else {
            "enum"
        };
        self.writeln(&format!("const {} = union({}) {{", e.ident.sym, enum_type));
        self.indent();
        for v in &e.variants {
            let mut line = v.ident.sym.clone();
            if let Some(val) = &v.value {
                line.push_str(" = ");
                line.push_str(&self.generate_expr(val));
            }
            if let Some(fields) = &v.fields {
                line.push_str(": struct {");
                self.writeln(&line);
                self.indent();
                for f in fields {
                    self.writeln(&format!("{}: {},", f.ident.sym, self.map_type(&f.ty)));
                }
                self.dedent();
                self.writeln("},");
            } else {
                line.push(',');
                self.writeln(&line);
            }
        }
        self.dedent();
        self.writeln("};\n");
    }

